// Sites come from TypeScript's own parser and never from a scan of the text,
// so a comment or the contents of a string is never a site. The same parser
// reads JavaScript. What is left out, and why:
//
//   - types: an interface, a type alias, an annotation, an ambient
//     declaration, an enum. A literal there is structure, not a value;
//   - imports, exports, decorators, a directive such as "use strict", the
//     name of a property, and the specifier a `require` or `import()` names;
//   - the labels of a `case`, where a changed literal repeats a case;
//   - the strings of JSX attributes, which are markup;
//   - an in-source test block, `if (import.meta.vitest)`;
//   - anything in a call `exclude_calls` names, and that call itself;
//   - `super(...)`, which a derived class's constructor cannot do without.

import { createHash } from "node:crypto";
import ts from "typescript";
import type { Site, Spell } from "./protocol";
import { Source } from "./source";

export class ParseError extends Error {}

interface Candidate {
  from: number;
  to: number;
  spell: Spell;
  replacement: string;
  enclosing: string;
}

const COMPARE = new Map<ts.SyntaxKind, string>([
  [ts.SyntaxKind.LessThanToken, "<="],
  [ts.SyntaxKind.LessThanEqualsToken, "<"],
  [ts.SyntaxKind.GreaterThanToken, ">="],
  [ts.SyntaxKind.GreaterThanEqualsToken, ">"],
  [ts.SyntaxKind.EqualsEqualsEqualsToken, "!=="],
  [ts.SyntaxKind.ExclamationEqualsEqualsToken, "==="],
  [ts.SyntaxKind.EqualsEqualsToken, "!="],
  [ts.SyntaxKind.ExclamationEqualsToken, "=="],
]);

const CONNECT = new Map<ts.SyntaxKind, string>([
  [ts.SyntaxKind.AmpersandAmpersandToken, "||"],
  [ts.SyntaxKind.BarBarToken, "&&"],
]);

/** The script kind a file is parsed as, from its extension; undefined for a file that is not code. */
export function scriptKind(file: string): ts.ScriptKind | undefined {
  const ext = /\.[^./]+$/.exec(file)?.[0] ?? "";
  switch (ext) {
    case ".ts":
    case ".mts":
    case ".cts":
      return ts.ScriptKind.TS;
    case ".tsx":
      return ts.ScriptKind.TSX;
    case ".js":
    case ".mjs":
    case ".cjs":
      return ts.ScriptKind.JS;
    case ".jsx":
      return ts.ScriptKind.JSX;
  }
  return undefined;
}

/** Parses a file, or throws a `ParseError` with what the parser said. */
export function parse(file: string, text: string, kind: ts.ScriptKind): ts.SourceFile {
  const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind);
  const said = (sf as unknown as { parseDiagnostics: readonly ts.Diagnostic[] }).parseDiagnostics;
  if (said.length > 0) {
    const d = said[0]!;
    const { line, character } = sf.getLineAndCharacterOfPosition(d.start ?? 0);
    throw new ParseError(`${line + 1}:${character + 1}: ${ts.flattenDiagnosticMessageText(d.messageText, "\n")}`);
  }
  return sf;
}

/** True when a file says it was generated by a tool, which nobody edits by hand. */
export function generated(text: string): boolean {
  const head = text.slice(0, 2048);
  return /@generated\b|\bDO NOT EDIT\b|\bCode generated by\b/.test(head);
}

/** Searches one file, already read. */
export function findSites(file: string, text: string, spells: Spell[], excludeCalls: string[]): Site[] {
  const kind = scriptKind(file);
  if (kind === undefined) throw new ParseError(`\`${file}\` is not TypeScript or JavaScript`);
  const sf = parse(file, text, kind);
  const walker = new Walker(sf, new Set(spells), excludeCalls, kind);
  walker.walk(sf, "<module>");
  return numbered(file, text, walker.kept());
}

class Walker {
  readonly found: Candidate[] = [];

  constructor(
    private readonly sf: ts.SourceFile,
    private readonly wanted: Set<Spell>,
    private readonly exclude: string[],
    private readonly kind: ts.ScriptKind,
  ) {}

  private propose(spell: Spell, from: number, to: number, replacement: string, enclosing: string): void {
    if (this.wanted.has(spell)) this.found.push({ from, to, spell, replacement, enclosing });
  }

  private text(n: ts.Node): string {
    return this.sf.text.slice(n.getStart(this.sf), n.getEnd());
  }

  walk(node: ts.Node, enclosing: string): void {
    if (this.silent(node)) return;
    const inner = this.named(node, enclosing);
    this.visit(node, inner);
    ts.forEachChild(node, (child) => {
      if (!this.noLiteralChild(node, child)) {
        this.walk(child, inner);
        return;
      }
      this.walkWithout(child, inner);
    });
  }

  // A child where only literals are out of place: a `case` label, a
  // property's name. Its other sites are still sites.
  private walkWithout(node: ts.Node, enclosing: string): void {
    const before = this.found.length;
    this.walk(node, enclosing);
    const start = node.getStart(this.sf);
    const end = node.getEnd();
    for (let i = this.found.length - 1; i >= before; i--) {
      const c = this.found[i]!;
      if (c.spell === "literal" && c.from >= start && c.to <= end) this.found.splice(i, 1);
    }
  }

  private silent(node: ts.Node): boolean {
    if (ts.isTypeNode(node) && !ts.isExpressionWithTypeArguments(node)) return true;
    if (
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isEnumDeclaration(node) ||
      ts.isImportDeclaration(node) ||
      ts.isImportEqualsDeclaration(node) ||
      ts.isExportDeclaration(node) ||
      ts.isDecorator(node)
    ) {
      return true;
    }
    if (ts.isJsxAttribute(node)) return this.markup(node);
    if (ambient(node)) return true;
    if (ts.isIfStatement(node) && inSourceTests(node.expression)) return true;
    if (ts.isCallExpression(node) && this.excluded(node)) return true;
    if (ts.isExpressionStatement(node) && directive(node)) return true;
    return false;
  }

  // A JSX attribute whose value is a string is markup; one whose value is an
  // expression is code, and its sites are sites.
  private markup(node: ts.JsxAttribute): boolean {
    return node.initializer === undefined || ts.isStringLiteral(node.initializer);
  }

  private noLiteralChild(parent: ts.Node, child: ts.Node): boolean {
    if (ts.isCaseClause(parent) && child === parent.expression) return true;
    if (
      (ts.isPropertyAssignment(parent) || ts.isPropertyDeclaration(parent) || ts.isMethodDeclaration(parent)) &&
      child === parent.name
    ) {
      return true;
    }
    if (ts.isGetAccessor(parent) || ts.isSetAccessor(parent)) return child === parent.name;
    if (ts.isCallExpression(parent) && moduleCall(parent) && child === parent.arguments[0]) return true;
    if (ts.isElementAccessExpression(parent) && child === parent.argumentExpression && ts.isStringLiteral(child))
      return true;
    return false;
  }

  private visit(node: ts.Node, enclosing: string): void {
    if (ts.isBinaryExpression(node)) {
      const op = node.operatorToken;
      const compare = COMPARE.get(op.kind);
      if (compare !== undefined) this.propose("compare", op.getStart(this.sf), op.getEnd(), compare, enclosing);
      const connect = CONNECT.get(op.kind);
      if (connect !== undefined) this.propose("connect", op.getStart(this.sf), op.getEnd(), connect, enclosing);
      return;
    }
    if (ts.isIfStatement(node) || ts.isWhileStatement(node) || ts.isDoStatement(node)) {
      this.negate(node.expression, enclosing);
      return;
    }
    if (ts.isForStatement(node)) {
      if (node.condition !== undefined) this.negate(node.condition, enclosing);
      return;
    }
    if (ts.isConditionalExpression(node)) {
      this.negate(node.condition, enclosing);
      return;
    }
    if (ts.isPrefixUnaryExpression(node) && node.operator === ts.SyntaxKind.ExclamationToken) {
      this.propose("negate", node.getStart(this.sf), node.getEnd(), this.text(node.operand), enclosing);
      return;
    }
    if (ts.isCaseBlock(node)) {
      this.arms(node, enclosing);
      return;
    }
    if (ts.isExpressionStatement(node)) {
      this.call(node, enclosing);
      return;
    }
    if (ts.isNumericLiteral(node)) {
      this.integer(node, enclosing);
      return;
    }
    if (node.kind === ts.SyntaxKind.TrueKeyword || node.kind === ts.SyntaxKind.FalseKeyword) {
      const flipped = node.kind === ts.SyntaxKind.TrueKeyword ? "false" : "true";
      this.propose("literal", node.getStart(this.sf), node.getEnd(), flipped, enclosing);
      return;
    }
    if (ts.isStringLiteral(node) && node.text !== "") {
      const quote = this.text(node)[0] === "'" ? "''" : '""';
      this.propose("literal", node.getStart(this.sf), node.getEnd(), quote, enclosing);
    }
  }

  // A condition that is already `!c` is negated by dropping the `!`, which
  // the operator itself proposes: `!(!c)` would be the same wekufe twice.
  private negate(cond: ts.Expression, enclosing: string): void {
    if (ts.isPrefixUnaryExpression(cond) && cond.operator === ts.SyntaxKind.ExclamationToken) return;
    this.propose("negate", cond.getStart(this.sf), cond.getEnd(), `!(${this.text(cond)})`, enclosing);
  }

  // Only a plain decimal integer has an obvious neighbour; `0x1F`, `1_000`,
  // `1e3` and `0755` are written that way to mean something about their
  // digits, and `10n` is a bigint whose type a neighbour keeps but whose
  // reader does not expect one.
  private integer(node: ts.NumericLiteral, enclosing: string): void {
    const written = this.text(node);
    if (!/^(0|[1-9][0-9]*)$/.test(written)) return;
    const next = (BigInt(written) + 1n).toString();
    this.propose("literal", node.getStart(this.sf), node.getEnd(), next, enclosing);
  }

  // Every clause of a switch but `default` and the last: the last is the one
  // a switch is most often written to fall to.
  private arms(block: ts.CaseBlock, enclosing: string): void {
    block.clauses.forEach((clause, i) => {
      if (ts.isDefaultClause(clause) || i === block.clauses.length - 1) return;
      this.propose("arm", clause.getStart(this.sf), clause.getEnd(), "", enclosing);
    });
  }

  // A call that is a whole statement, awaited or not, becomes an empty
  // statement: `;` keeps the statements around it apart where a line with
  // no semicolon would otherwise run into the next.
  private call(stmt: ts.ExpressionStatement, enclosing: string): void {
    let e: ts.Expression = stmt.expression;
    if (ts.isAwaitExpression(e)) e = e.expression;
    if (!ts.isCallExpression(e)) return;
    if (e.expression.kind === ts.SyntaxKind.SuperKeyword || e.expression.kind === ts.SyntaxKind.ImportKeyword) return;
    if (this.excluded(e)) return;
    this.propose("call", stmt.getStart(this.sf), stmt.getEnd(), ";", enclosing);
  }

  private excluded(call: ts.CallExpression): boolean {
    const name = callee(call.expression);
    return name !== "" && this.exclude.some((p) => matches(name, p));
  }

  // The name of what a node declares, for `enclosing`: `parse`, `Parser.next`,
  // `Parser.constructor`, `handlers.onClick`. A function nobody named is
  // `<anonymous>` inside whatever encloses it.
  private named(node: ts.Node, enclosing: string): string {
    const within = (name: string): string => (enclosing === "<module>" ? name : `${enclosing}.${name}`);
    if (ts.isFunctionDeclaration(node) || ts.isClassDeclaration(node) || ts.isModuleDeclaration(node)) {
      return within(node.name ? nameOf(node.name) : "default");
    }
    if (ts.isMethodDeclaration(node) || ts.isGetAccessor(node) || ts.isSetAccessor(node)) {
      const prefix = ts.isGetAccessor(node) ? "get " : ts.isSetAccessor(node) ? "set " : "";
      return within(prefix + nameOf(node.name));
    }
    if (ts.isConstructorDeclaration(node)) return within("constructor");
    if (ts.isPropertyDeclaration(node) || ts.isPropertyAssignment(node) || ts.isVariableDeclaration(node)) {
      return names(node.initializer) ? within(nameOf(node.name)) : enclosing;
    }
    if (ts.isFunctionExpression(node) || ts.isArrowFunction(node) || ts.isClassExpression(node)) {
      const parent = node.parent;
      const namedByParent =
        (ts.isVariableDeclaration(parent) || ts.isPropertyDeclaration(parent) || ts.isPropertyAssignment(parent)) &&
        parent.initializer === node;
      if (namedByParent) return enclosing;
      if ((ts.isFunctionExpression(node) || ts.isClassExpression(node)) && node.name) return within(node.name.text);
      return within("<anonymous>");
    }
    return enclosing;
  }

  /** The candidates in source order, each once, with an `arm` that still parses. */
  kept(): Candidate[] {
    const seen = new Set<string>();
    const out: Candidate[] = [];
    for (const c of this.found) {
      const key = `${c.from}|${c.to}|${c.spell}|${c.replacement}`;
      if (seen.has(key)) continue;
      seen.add(key);
      if (c.spell === "arm" && !this.stillParses(c)) continue;
      out.push(c);
    }
    return out.sort(
      (a, b) => a.from - b.from || a.to - b.to || cmp(a.spell, b.spell) || cmp(a.replacement, b.replacement),
    );
  }

  private stillParses(c: Candidate): boolean {
    const text = this.sf.text.slice(0, c.from) + c.replacement + this.sf.text.slice(c.to);
    try {
      parse(this.sf.fileName, text, this.kind);
      return true;
    } catch {
      return false;
    }
  }
}

function cmp(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function nameOf(name: ts.PropertyName | ts.BindingName | ts.ModuleName): string {
  if (ts.isIdentifier(name) || ts.isPrivateIdentifier(name)) return name.text;
  if (ts.isStringLiteral(name) || ts.isNumericLiteral(name)) return name.text;
  return "<computed>";
}

// What a declaration's name is the name of: a function, a class, or an
// object whose methods are known by it, as `handlers.onClick`.
function names(e: ts.Expression | undefined): boolean {
  return (
    e !== undefined &&
    (ts.isArrowFunction(e) || ts.isFunctionExpression(e) || ts.isClassExpression(e) || ts.isObjectLiteralExpression(e))
  );
}

function ambient(node: ts.Node): boolean {
  if (!ts.canHaveModifiers(node)) return false;
  return (ts.getModifiers(node) ?? []).some((m) => m.kind === ts.SyntaxKind.DeclareKeyword);
}

// `if (import.meta.vitest)`, the block Vitest runs a file's in-source tests from.
function inSourceTests(e: ts.Expression): boolean {
  return (
    ts.isPropertyAccessExpression(e) &&
    e.name.text === "vitest" &&
    ts.isMetaProperty(e.expression) &&
    e.expression.keywordToken === ts.SyntaxKind.ImportKeyword
  );
}

// "use strict" and its kind, which only mean something as strings.
function directive(stmt: ts.ExpressionStatement): boolean {
  if (!ts.isStringLiteral(stmt.expression)) return false;
  const parent = stmt.parent;
  if (!ts.isSourceFile(parent) && !ts.isBlock(parent)) return false;
  for (const s of parent.statements) {
    if (s === stmt) return true;
    if (!ts.isExpressionStatement(s) || !ts.isStringLiteral(s.expression)) return false;
  }
  return false;
}

// `require("x")`, `import("x")`, `jest.mock("x")`, `vi.mock("x")`: the first
// argument names a module.
function moduleCall(call: ts.CallExpression): boolean {
  if (call.expression.kind === ts.SyntaxKind.ImportKeyword) return true;
  const name = callee(call.expression);
  return [
    "require",
    "require.resolve",
    "jest.mock",
    "jest.doMock",
    "jest.unmock",
    "jest.requireActual",
    "vi.mock",
    "vi.doMock",
    "vi.unmock",
    "vi.importActual",
  ].includes(name);
}

/** The name a call is matched against `exclude_calls` by: `console.log`, `this.logger.info`. */
export function callee(e: ts.Expression): string {
  if (ts.isIdentifier(e)) return e.text;
  if (e.kind === ts.SyntaxKind.ThisKeyword) return "this";
  if (ts.isPropertyAccessExpression(e)) {
    const head = callee(e.expression);
    return head === "" ? "" : `${head}.${e.name.text}`;
  }
  if (ts.isNonNullExpression(e) || ts.isParenthesizedExpression(e)) return callee(e.expression);
  return "";
}

/** An exact name, or a prefix ending in `*`. */
export function matches(name: string, pattern: string): boolean {
  if (!pattern.endsWith("*")) return name === pattern;
  const head = pattern.slice(0, -1);
  return !head.includes("*") && name.startsWith(head);
}

// The ordinal is the 1-based occurrence of (spell, original) within the
// enclosing declaration, in source order: what lets a declared equivalent
// survive an edit elsewhere in the file, where a line number would not.
function numbered(file: string, text: string, kept: Candidate[]): Site[] {
  const src = new Source(text);
  const fileHash = createHash("sha256").update(text, "utf8").digest("hex");
  const seen = new Map<string, number>();
  return kept.map((c) => {
    const original = text.slice(c.from, c.to);
    const key = `${c.enclosing}\u0000${c.spell}\u0000${original}`;
    const ordinal = (seen.get(key) ?? 0) + 1;
    seen.set(key, ordinal);
    const start = src.position(c.from);
    const end = src.position(c.to);
    const id = createHash("sha256")
      .update(`${fileHash}|${start.byte}|${end.byte}|${c.spell}|${c.replacement}`, "utf8")
      .digest("hex")
      .slice(0, 12);
    return {
      site_id: id,
      file,
      enclosing: c.enclosing,
      ordinal,
      start,
      end,
      spell: c.spell,
      original,
      replacement: c.replacement,
      reload: "module",
    };
  });
}
