package kalku

import (
	"errors"
	"testing"
)

func originals(t *testing.T, text string, spells ...string) []string {
	t.Helper()
	sites, err := FindSites("f.go", text, spells, nil)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, s := range sites {
		out = append(out, *s.Original+" -> "+s.Replacement)
	}
	return out
}

func TestAGeneratedFileIsNotSearched(t *testing.T) {
	_, err := FindSites("f.go", "// Code generated by stringer. DO NOT EDIT.\n\npackage p\n\nvar x = 1 > 0\n", Spells, nil)
	if !errors.Is(err, ErrGenerated) {
		t.Fatalf("got %v", err)
	}
}

func TestAFileThatIsNotGoSaysWhere(t *testing.T) {
	_, err := FindSites("f.go", "package p\n\nfunc (\n", Spells, nil)
	var p *ParseError
	if !errors.As(err, &p) || p.Message == "" {
		t.Fatalf("got %v", err)
	}
}

// Only the spells asked for are proposed.
func TestOnlyTheSpellsAskedForAreProposed(t *testing.T) {
	got := originals(t, "package p\n\nfunc f(a int) bool { return a > 1 && true }\n", "connect")
	if len(got) != 1 || got[0] != "&& -> ||" {
		t.Fatalf("got %v", got)
	}
}

// A site id is the same for the same file and changes when the file does.
func TestASiteIDIsStableForTheSameFile(t *testing.T) {
	a, _ := FindSites("f.go", "package p\n\nvar x = 1 > 0\n", []string{"compare"}, nil)
	b, _ := FindSites("f.go", "package p\n\nvar x = 1 > 0\n", []string{"compare"}, nil)
	c, _ := FindSites("f.go", "package p\n\nvar x = 2 > 0\n", []string{"compare"}, nil)
	if a[0].SiteID != b[0].SiteID || a[0].SiteID == c[0].SiteID || len(a[0].SiteID) != 12 {
		t.Fatalf("%s %s %s", a[0].SiteID, b[0].SiteID, c[0].SiteID)
	}
}

// Columns count characters, bytes count bytes.
func TestAColumnCountsCharactersAndAByteCountsBytes(t *testing.T) {
	sites, _ := FindSites("f.go", "package p\n\nvar s, ok = \"ñandú\", 1 > 0\n", []string{"compare"}, nil)
	if got := sites[0].Start; got.Line != 3 || got.Col != 24 || got.Byte != 36 {
		t.Fatalf("got %+v", got)
	}
}

func TestExcludeCallsMatchesANameOrAPrefix(t *testing.T) {
	cases := []struct {
		name, pattern string
		want          bool
	}{
		{"log.Printf", "log.*", true},
		{"log.Printf", "log.Printf", true},
		{"logger.Info", "log.*", false},
		{"s.log.Info", "s.log.*", true},
		{"fmt.Println", "fmt.Print", false},
		{"a.b", "*.b", false},
	}
	for _, c := range cases {
		if got := matches(c.name, c.pattern); got != c.want {
			t.Errorf("matches(%q, %q) = %v", c.name, c.pattern, got)
		}
	}
}

// An import is known by what its path ends in, without a major version or
// a `go-`, or by the name it is given.
func TestAnImportIsKnownByTheNameItIsUsedBy(t *testing.T) {
	text := "package p\n\nimport (\n\t\"gopkg.in/yaml.v3\"\n\t\"github.com/x/go-sqlite3\"\n\t\"example.com/m/v2\"\n\tj \"encoding/json\"\n)\n"
	sites, err := FindSites("f.go", text+"\nfunc f() {\n\tyaml.A()\n\tsqlite3.B()\n\tm.C()\n\tj.D()\n}\n", []string{"call"}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(sites) != 0 {
		t.Fatalf("each call is the last use of its import, yet: %v", sites)
	}
}

// A variable assigned or incremented elsewhere is still unused there.
func TestAWriteIsNotAUse(t *testing.T) {
	got := originals(t, "package p\n\nfunc f() {\n\tn := 0\n\tn = 2\n\tn++\n\tg(n)\n}\n", "call")
	if len(got) != 0 {
		t.Fatalf("got %v", got)
	}
}

// A variable declared inside the call goes with it; inside, the call that
// is its last use stays.
func TestAVariableDeclaredInTheCallGoesWithIt(t *testing.T) {
	got := originals(t, "package p\n\nfunc f() {\n\tg(func() { v := 1; h(v) })\n}\n", "call")
	if len(got) != 1 || got[0] != "g(func() { v := 1; h(v) }) -> " {
		t.Fatalf("got %v", got)
	}
}

// A function literal a package variable holds has locals of its own.
func TestALiteralInAPackageVariableHasLocalsOfItsOwn(t *testing.T) {
	got := originals(t, "package p\n\nvar f = func() {\n\tv := 1\n\th(v)\n\tg()\n}\n", "call")
	if len(got) != 1 || got[0] != "g() -> " {
		t.Fatalf("got %v", got)
	}
}
