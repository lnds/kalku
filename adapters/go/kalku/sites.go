// Sites come from Go's own parser and never from a scan of the text, so a
// comment or the contents of a string is never a site. What is left out,
// and why:
//
//   - a file the compiler is told is generated, which nobody edits;
//   - integers in an array's length, in a `case` list or as a key of a
//     composite literal: changing one changes a type or repeats a case,
//     which is a compile error no test has an opinion about;
//   - anything in a call `exclude_calls` names, and that call itself;
//   - a call statement whose removal would leave an import or a variable
//     unused, and a `panic` that ends its block, whose removal would leave
//     a function without a return: each is a compile error, not a wekufe;
//   - a wekufe that is not Go any more.

// ParseError is a file that is not Go.
type ParseError struct{ Message string }

func (e *ParseError) Error() string { return e.Message }

// ErrGenerated is a file generated by a tool, which says so.
var ErrGenerated = fmt.Errorf("the file says it is generated, and nobody edits it by hand")

type candidate struct {
	from, to    int
	spell       string
	replacement string
	enclosing   string
}

// FindSites searches one file.
func FindSites(file, text string, spells, excludeCalls []string) ([]Site, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, file, text, parser.ParseComments)
	if err != nil {
		return nil, &ParseError{Message: err.Error()}
	}
	if ast.IsGenerated(f) {
		return nil, ErrGenerated
	}
	w := &walker{
		fset:    fset,
		file:    f,
		text:    text,
		wanted:  map[string]bool{},
		exclude: excludeCalls,
		pkg:     f.Name.Name,
	}
	for _, s := range spells {
		w.wanted[s] = true
	}
	for _, d := range f.Decls {
		w.decl(d)
	}
	src := newSource(text)
	return number(file, text, src, w.kept()), nil
}

type span struct{ from, to int }

type walker struct {
	fset      *token.FileSet
	file      *ast.File
	text      string
	wanted    map[string]bool
	exclude   []string
	pkg       string
	enclosing string
	body      span // the function being walked, for what is local to it
	found     []candidate
	// Where no site goes, and where no literal does.
	silent    []span
	noLiteral []span
	idents    []use
}

func (w *walker) offset(p token.Pos) int { return w.fset.Position(p).Offset }

func (w *walker) spanOf(n ast.Node) span { return span{w.offset(n.Pos()), w.offset(n.End())} }

func (w *walker) propose(spell string, from, to int, replacement string) {
	if !w.wanted[spell] {
		return
	}
	w.found = append(w.found, candidate{from, to, spell, replacement, w.enclosing})
}

func (w *walker) decl(d ast.Decl) {
	switch d := d.(type) {
	case *ast.FuncDecl:
		if d.Body == nil {
			return
		}
		w.enclosing = w.pkg + "." + funcName(d)
		w.body = w.spanOf(d.Body)
		w.returns(d.Type, d.Body)
		w.walk(d.Body)
	case *ast.GenDecl:
		if d.Tok != token.VAR && d.Tok != token.CONST {
			return
		}
		for _, s := range d.Specs {
			v := s.(*ast.ValueSpec)
			w.enclosing = w.pkg + "." + v.Names[0].Name
			// What a function literal in the value declares is local to it;
			// the names the declaration gives are the package's.
			w.body = span{}
			if len(v.Values) > 0 {
				w.body = span{w.offset(v.Values[0].Pos()), w.offset(v.Values[len(v.Values)-1].End())}
			}
			for _, e := range v.Values {
				w.walk(e)
			}
		}
	}
}

// `Parse`, `(*Parser).Next`, `Stack.Len`: a method with its receiver's type
// as Go writes it in a method expression, and without type parameters.
func funcName(d *ast.FuncDecl) string {
	if d.Recv == nil || len(d.Recv.List) == 0 {
		return d.Name.Name
	}
	t := d.Recv.List[0].Type
	pointer := false
	if star, ok := t.(*ast.StarExpr); ok {
		pointer, t = true, star.X
	}
	switch g := t.(type) {
	case *ast.IndexExpr:
		t = g.X
	case *ast.IndexListExpr:
		t = g.X
	}
	name := "?"
	if id, ok := t.(*ast.Ident); ok {
		name = id.Name
	}
	if pointer {
		return "(*" + name + ")." + d.Name.Name
	}
	return name + "." + d.Name.Name
}

func (w *walker) walk(root ast.Node) {
	ast.Inspect(root, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.FuncLit:
			w.returns(n.Type, n.Body)
			return true
		case *ast.CallExpr:
			if w.excluded(n) {
				w.silent = append(w.silent, w.spanOf(n))
				return false
			}
		case *ast.ArrayType:
			if n.Len != nil {
				w.noLiteral = append(w.noLiteral, w.spanOf(n.Len))
			}
		case *ast.CaseClause:
			for _, e := range n.List {
				w.noLiteral = append(w.noLiteral, w.spanOf(e))
			}
			w.statements(n.Body)
		case *ast.CommClause:
			w.statements(n.Body)
		case *ast.KeyValueExpr:
			w.noLiteral = append(w.noLiteral, w.spanOf(n.Key))
		case *ast.BlockStmt:
			w.statements(n.List)
		case *ast.BinaryExpr:
			w.binary(n)
		case *ast.IfStmt:
			w.negate(n.Cond)
		case *ast.ForStmt:
			if n.Cond != nil {
				w.negate(n.Cond)
			}
		case *ast.SwitchStmt:
			w.arms(n.Body)
		case *ast.TypeSwitchStmt:
			w.arms(n.Body)
		case *ast.BasicLit:
			w.integer(n)
		case *ast.Ident:
			if (n.Name == "true" || n.Name == "false") && n.Obj == nil {
				flipped := map[string]string{"true": "false", "false": "true"}[n.Name]
				s := w.spanOf(n)
				w.propose("literal", s.from, s.to, flipped)
			}
		}
		return true
	})
}

var flips = map[token.Token]string{
	token.GEQ:  ">",
	token.GTR:  ">=",
	token.LEQ:  "<",
	token.LSS:  "<=",
	token.EQL:  "!=",
	token.NEQ:  "==",
	token.LAND: "||",
	token.LOR:  "&&",
}

func (w *walker) binary(b *ast.BinaryExpr) {
	to, ok := flips[b.Op]
	if !ok {
		return
	}
	spell := "compare"
	if b.Op == token.LAND || b.Op == token.LOR {
		spell = "connect"
	}
	from := w.offset(b.OpPos)
	w.propose(spell, from, from+len(b.Op.String()), to)
}

func (w *walker) negate(cond ast.Expr) {
	s := w.spanOf(cond)
	w.propose("negate", s.from, s.to, "!("+w.text[s.from:s.to]+")")
}

// Only a plain decimal integer has an obvious neighbour; `0x1F`, `0o17`,
// `0755` and `1_000` are written that way to mean something about their
// digits. The neighbour is the next integer, unless the integer is the
// largest of a sized type: `255` is most often a byte, where `256` does not
// compile, so its neighbour is `254`.
func (w *walker) integer(l *ast.BasicLit) {
	if l.Kind != token.INT {
		return
	}
	v := l.Value
	if strings.ContainsAny(v, "xXoObB_") || (len(v) > 1 && v[0] == '0') {
		return
	}
	n, err := strconv.ParseUint(v, 10, 64)
	if err != nil {
		return
	}
	next := n + 1
	if largest[n] {
		next = n - 1
	}
	s := w.spanOf(l)
	w.propose("literal", s.from, s.to, strconv.FormatUint(next, 10))
}

// The largest value of each sized integer type.
var largest = map[uint64]bool{
	1<<7 - 1: true, 1<<8 - 1: true, 1<<15 - 1: true, 1<<16 - 1: true,
	1<<31 - 1: true, 1<<32 - 1: true, 1<<63 - 1: true, 1<<64 - 1: true,
}

// Every clause of a switch but `default` and the last: the last is the one
// a switch is most often written to fall to.
func (w *walker) arms(body *ast.BlockStmt) {
	for i, s := range body.List {
		c := s.(*ast.CaseClause)
		if c.List == nil || i == len(body.List)-1 {
			continue
		}
		sp := w.spanOf(c)
		w.propose("arm", sp.from, sp.to, "")
	}
}

func (w *walker) statements(list []ast.Stmt) {
	for i, s := range list {
		e, ok := s.(*ast.ExprStmt)
		if !ok {
			continue
		}
		call, ok := e.X.(*ast.CallExpr)
		if !ok || w.excluded(call) {
			continue
		}
		if isPanic(call) && i == len(list)-1 {
			continue
		}
		if w.leavesUnused(e) {
			continue
		}
		sp := w.spanOf(e)
		w.propose("call", sp.from, sp.to, "")
	}
}

func isPanic(c *ast.CallExpr) bool {
	id, ok := c.Fun.(*ast.Ident)
	return ok && id.Name == "panic" && id.Obj == nil
}

// The name a call is matched against `exclude_calls` by: `log.Printf`,
// `s.logger.Info`, `fmt.Println`.
func callee(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.Ident:
		return e.Name
	case *ast.SelectorExpr:
		if head := callee(e.X); head != "" {
			return head + "." + e.Sel.Name
		}
	case *ast.IndexExpr:
		return callee(e.X)
	case *ast.IndexListExpr:
		return callee(e.X)
	}
	return ""
}

func (w *walker) excluded(c *ast.CallExpr) bool {
	name := callee(c.Fun)
	if name == "" {
		return false
	}
	for _, p := range w.exclude {
		if matches(name, p) {
			return true
		}
	}
	return false
}

// An exact name, or a prefix ending in `*`.
func matches(name, pattern string) bool {
	head, found := strings.CutSuffix(pattern, "*")
	if !found {
		return name == pattern
	}
	return !strings.Contains(head, "*") && strings.HasPrefix(name, head)
}

// use is an identifier of the file, as the check for what a removed call
// leaves unused reads it: whether it names a package before a `.`, and
// whether it is read rather than declared or only written to.
type use struct {
	id        *ast.Ident
	at        int
	qualifier bool
	read      bool
}

// The file's identifiers, gathered once.
func (w *walker) uses() []use {
	if w.idents != nil {
		return w.idents
	}
	assigned := w.assignedOnly()
	qualifiers := map[*ast.Ident]bool{}
	w.idents = []use{}
	ast.Inspect(w.file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok && id.Obj == nil {
				qualifiers[id] = true
			}
		case *ast.Ident:
			declared := n.Obj != nil && n.Pos() == n.Obj.Pos()
			w.idents = append(w.idents, use{
				id:        n,
				at:        w.offset(n.Pos()),
				qualifier: qualifiers[n],
				read:      n.Obj != nil && !declared && !assigned[n],
			})
		}
		return true
	})
	return w.idents
}

// True when the node holds the last use of an import or of a local
// variable, which Go refuses to leave unused.
func (w *walker) leavesUnused(stmt ast.Node) bool {
	in := w.spanOf(stmt)
	packages := map[string]bool{}
	locals := map[*ast.Object]bool{}
	imported := w.imported()
	ast.Inspect(stmt, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.SelectorExpr:
			if id, ok := n.X.(*ast.Ident); ok && id.Obj == nil && imported[id.Name] {
				packages[id.Name] = true
			}
		case *ast.Ident:
			if w.isLocal(n.Obj) && !in.holds(w.offset(n.Obj.Pos())) {
				locals[n.Obj] = true
			}
		}
		return true
	})
	if len(packages) == 0 && len(locals) == 0 {
		return false
	}
	usedElsewhere := map[string]bool{}
	localElsewhere := map[*ast.Object]bool{}
	for _, u := range w.uses() {
		if in.holds(u.at) {
			continue
		}
		if u.qualifier && packages[u.id.Name] {
			usedElsewhere[u.id.Name] = true
		}
		if u.read && locals[u.id.Obj] {
			localElsewhere[u.id.Obj] = true
		}
	}
	for p := range packages {
		if !usedElsewhere[p] {
			return true
		}
	}
	for o := range locals {
		if !localElsewhere[o] {
			return true
		}
	}
	return false
}

// The names this file's imports are likely known by: the name an import
// gives, or the last element of its path without a major version or a
// `go-` in front. A guess that misses costs a compile error, not a result.
func (w *walker) imported() map[string]bool {
	out := map[string]bool{}
	for _, spec := range w.file.Imports {
		if spec.Name != nil {
			out[spec.Name.Name] = true
			continue
		}
		path, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			continue
		}
		parts := strings.Split(path, "/")
		last := parts[len(parts)-1]
		if len(parts) > 1 && isMajor(last) {
			last = parts[len(parts)-2]
		}
		if dot := strings.LastIndex(last, ".v"); dot > 0 && isMajor(last[dot+1:]) {
			last = last[:dot]
		}
		last = strings.TrimPrefix(last, "go-")
		out[strings.ReplaceAll(last, "-", "_")] = true
		out[last] = true
	}
	return out
}

// `v2`, `v10`: the element a module path ends in from its second major
// version on.
func isMajor(s string) bool {
	if len(s) < 2 || s[0] != 'v' {
		return false
	}
	_, err := strconv.Atoi(s[1:])
	return err == nil
}

// A variable declared inside the function being walked, as opposed to a
// parameter, a result, or one of the package's.
func (w *walker) isLocal(o *ast.Object) bool {
	if o == nil || o.Kind != ast.Var {
		return false
	}
	if _, field := o.Decl.(*ast.Field); field {
		return false
	}
	return w.body.holds(w.offset(o.Pos()))
}

// The identifiers that are only written to: the left of `=` or `+=`, and
// the operand of `++`. Go does not count either as a use.
func (w *walker) assignedOnly() map[*ast.Ident]bool {
	out := map[*ast.Ident]bool{}
	ast.Inspect(w.file, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.AssignStmt:
			if n.Tok != token.DEFINE {
				for _, l := range n.Lhs {
					if id, ok := l.(*ast.Ident); ok {
						out[id] = true
					}
				}
			}
		case *ast.IncDecStmt:
			if id, ok := n.X.(*ast.Ident); ok {
				out[id] = true
			}
		}
		return true
	})
	return out
}

func (s span) holds(at int) bool { return s.from <= at && at < s.to }

func (s span) covers(o span) bool { return s.from <= o.from && o.to <= s.to }

// The candidates that survive the rules above, in source order, each once.
func (w *walker) kept() []candidate {
	type key struct {
		from, to    int
		spell, repl string
	}
	seen := map[key]bool{}
	var out []candidate
	for _, c := range w.found {
		k := key{c.from, c.to, c.spell, c.replacement}
		if seen[k] || w.hidden(c) || !w.stillGo(c) {
			continue
		}
		seen[k] = true
		out = append(out, c)
	}
	sort.SliceStable(out, func(i, j int) bool {
		a, b := out[i], out[j]
		if a.from != b.from {
			return a.from < b.from
		}
		if a.to != b.to {
			return a.to < b.to
		}
		if a.spell != b.spell {
			return a.spell < b.spell
		}
		return a.replacement < b.replacement
	})
	return out
}

func (w *walker) hidden(c candidate) bool {
	at := span{c.from, c.to}
	for _, s := range w.silent {
		if s.covers(at) {
			return true
		}
	}
	if c.spell == "literal" {
		for _, s := range w.noLiteral {
			if s.covers(at) {
				return true
			}
		}
	}
	return false
}

// A wekufe that does not parse would be a compile error for a reason that
// has nothing to do with the tests.
func (w *walker) stillGo(c candidate) bool {
	text := splice(w.text, c.from, c.to, c.replacement)
	_, err := parser.ParseFile(token.NewFileSet(), "", text, parser.SkipObjectResolution)
	return err == nil
}

// The ordinal is the 1-based occurrence of (spell, original) within the
// enclosing declaration, in source order: what lets a declared equivalent
// survive an edit elsewhere in the file, where a line number would not.
func number(file, text string, src *source, kept []candidate) []Site {
	hash := sha256.Sum256([]byte(text))
	fileHash := hex.EncodeToString(hash[:])
	type key struct{ enclosing, spell, original string }
	seen := map[key]int{}
	sites := make([]Site, 0, len(kept))
	for _, c := range kept {
		original := text[c.from:c.to]
		k := key{c.enclosing, c.spell, original}
		seen[k]++
		id := sha256.Sum256([]byte(fmt.Sprintf("%s|%d|%d|%s|%s", fileHash, c.from, c.to, c.spell, c.replacement)))
		end := src.position(c.to)
		sites = append(sites, Site{
			SiteID:      hex.EncodeToString(id[:])[:12],
			File:        file,
			Enclosing:   c.enclosing,
			Ordinal:     seen[k],
			Start:       src.position(c.from),
			End:         &end,
			Spell:       c.spell,
			Original:    &original,
			Replacement: c.replacement,
			Reload:      "module",
		})
	}
	return sites
}
